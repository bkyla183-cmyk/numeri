export function getCalculatorsInCategory(categorySlug: string, currentSlug?: string): CalculatorItem[] {
  return calculators.filter((c) => c.category_slug === categorySlug && c.slug !== currentSlug);
}

/**
 * Returns curated or cross-category companion tools that complement the current calculator
 */
export function getCompanionCalculators(
  currentSlug: string,
  categorySlug: string,
  limit = 8,
  preferredSlugs?: string[]
): CalculatorItem[] {
  const chosen: CalculatorItem[] = [];
  const seen = new Set<string>([currentSlug]);

  if (preferredSlugs && preferredSlugs.length > 0) {
    for (const slug of preferredSlugs) {
      if (chosen.length >= limit) break;
      if (seen.has(slug)) continue;
      const item = calculators.find((c) => c.slug === slug);
      if (item) {
        chosen.push(item);
        seen.add(slug);
      }
    }
  }

  for (const c of calculators) {
    if (chosen.length >= limit) break;
    if (seen.has(c.slug)) continue;
    if (c.category_slug !== categorySlug && (c.is_popular || c.is_featured)) {
      chosen.push(c);
      seen.add(c.slug);
    }
  }
  return chosen;
}

